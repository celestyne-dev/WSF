export const getArticleBySlug = (slug) => articles.find((a) => a.slug === slug && a.status === 'published')

export const getArticlesByTopic = (topicSlug) => articles.filter((a) => a.topicSlugs.includes(topicSlug))

export const getArticlesBySeries = (seriesSlug) => articles.filter((a) => a.seriesSlug === seriesSlug)

export const getArticlesByAuthor = (authorSlug) =>
  articles.filter((a) => a.authorSlug === authorSlug || a.coAuthorSlugs.includes(authorSlug))

export const getArticlesByPerson = (personSlug) => articles.filter((a) => a.relatedPersonSlugs.includes(personSlug))

export const getFeaturedArticles = () => articles.filter((a) => a.featured)

export const getLatestArticles = (limit = 20) =>
  [...articles].sort((a, b) => new Date(b.publishDate) - new Date(a.publishDate)).slice(0, limit)
