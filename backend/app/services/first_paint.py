def _pick_default_price(prices, default_currency):
    for test in (lambda p: p.get("currency") == default_currency and p.get("checkoutAvailable"),
                 lambda p: p.get("checkoutAvailable"), lambda p: p.get("currency") == default_currency):
        found = next((p for p in prices if test(p)), None)
        if found:
            return found
    return prices[0] if prices else None


def _first(r, *keys):
    for key in keys:
        if r.get(key):
            return r[key]
    return None


def resource_card(r):
    """cards/ResourceCard.jsx. The public Resource payload is camelCase
    (resources.build_public_resource_payload); this reads both spellings
    exactly as api/resources.js mapResource does."""
    access = _first(r, "access_type", "accessType") or "direct_download"
    level = _first(r, "circle_access_level", "circleAccessLevel") or "all_members"
    yearly_only = access == "circle_only" and level == "yearly_members"
    badge = ("sparkles11", "Circle Yearly & Lifetime") if yearly_only else _RESOURCE_BADGES.get(access)
    # mapResource: mapMediaRef(cover_media) || coverMedia. The camelCase
    # payload's coverMedia reaches MediaImage unmapped, so its alt falls back
    # to the resource name (resolveAltText reads `altText`).
    snake_media = r.get("cover_media") or None
    media = snake_media or r.get("coverMedia") or None
    alt = _alt(snake_media, r.get("name")) if snake_media else r.get("name") or ""
