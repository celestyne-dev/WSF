def public_nav_link(item):
    """utils/navigation.js publicNavLink()."""
    if not isinstance(item, dict):
        return None
    url = item.get("url") if isinstance(item.get("url"), str) and item.get("url") else None
    kind = item.get("linkType") or (
        "group" if item.get("itemType") == "group" or not url else ("external" if url.lower().startswith(("http://", "https://")) else "internal")
    )
    if kind == "group" or not url:
        return {"kind": "group"} if item.get("children") else None
    if kind == "external":
        return {"kind": "external", "href": url, "newTab": bool(item.get("openNewTab"))}
    return {"kind": "internal", "to": url}


def nav_path(link):
    if not link or link.get("kind") != "internal":
        return None
    path = link["to"].split("#")[0].split("?")[0].rstrip("/")
    return path or "/"


def _to_link(item):
    link = public_nav_link(item)
    return None if not link or link["kind"] == "group" else {"label": item.get("label"), "link": link}


def _flatten(item):
    own = _to_link(item)
    children = [c for c in (_to_link(ch) for ch in item.get("children") or []) if c]
    return ([own] if own else []) + children


def header_entries(navigation):
    """Top level of utils/megaMenu.js buildHeaderNavigation(): the visible
    entries in order, each {label, link, style, menu: bool, paths}."""
    menus = (navigation or {}).get("menus") or {}
    primary = (menus.get("primary") or {}).get("items") or []
    secondary = (menus.get("secondary") or {}).get("items") or []
    hosts, min_top = HEADER_MENU["hosts"], HEADER_MENU["minTopLevel"]

    entries = []
    for item in primary:
        link = public_nav_link(item)
        if not link:
            continue
        config = hosts.get(nav_path(link)) if link["kind"] == "internal" else None
        entries.append({"item": item, "link": link, "config": config})
    by_key = {e["config"]["key"]: e for e in entries if e["config"]}
    absorbed, visible = set(), len(entries)
    for i, e in enumerate(entries):
        if e["config"] or e["item"].get("style") == "cta" or visible <= min_top:
            continue
        path = nav_path(e["link"])
        if any(h["config"] and path in h["config"]["absorbs"] for h in entries):
            absorbed.add(i)
            visible -= 1
    extras = {}
    for i in absorbed:
        host = next(h for h in entries if h["config"] and nav_path(entries[i]["link"]) in h["config"]["absorbs"])
        extras.setdefault(id(host), []).extend(_flatten(entries[i]["item"]))
    menu_entries = [e for i, e in enumerate(entries) if i not in absorbed and (e["config"] or e["item"].get("children"))]
    fallback = by_key.get(HEADER_MENU["secondaryFallbackMenu"]) or (menu_entries[-1] if menu_entries else None)
    orphans = []
    for item in secondary:
        links = _flatten(item)
        if not links:
            continue
        host = by_key.get(HEADER_MENU["secondaryPlacement"].get(nav_path(links[0]["link"]))) or fallback
        if host is not None and entries.index(host) not in absorbed:
            extras.setdefault(id(host), []).extend(links)
        else:
            orphans.extend(links)

    result = []
    for i, e in enumerate(entries):
        if i in absorbed:
            continue
        child_links = [c for c in (_to_link(ch) for ch in e["item"].get("children") or []) if c]
        links = child_links + extras.get(id(e), [])
        is_menu = bool(e["config"]) or bool(links)
        paths = [nav_path(e["link"])] + [nav_path(l["link"]) for l in links]
        result.append({"label": e["item"].get("label") or "", "link": e["link"], "style": e["item"].get("style") or "standard",
                       "menu": is_menu, "paths": [p for p in paths if p]})
    for link in orphans:
        result.append({"label": link["label"] or "", "link": link["link"], "style": "standard", "menu": False,
                       "paths": [p for p in [nav_path(link["link"])] if p]})
    return result


def _is_active(entry, pathname):
    current = (pathname or "/").rstrip("/") or "/"
    return any(p != "/" and (current == p or current.startswith(p + "/")) for p in entry["paths"])


def _link_attrs(link):
    if link["kind"] == "external":
        rel = "noopener noreferrer" if link.get("newTab") else "noopener"
        target = ' target="_blank"' if link.get("newTab") else ""
        return f'href="{_a(link["href"])}"{target} rel="{rel}"'
    return f'href="{_a(link["to"])}"'


def render_header(navigation, logo_url=None, site_name="Women Shaping Futures", pathname="/"):
    """Header.jsx's first visual state for an anonymous visitor. Links work
    without JavaScript; menu triggers are links to their destination (or
    plain labels for a link-less group). The mobile menu icon is inert
    (decorative) until React mounts; render_noscript_nav keeps navigation
    reachable without JavaScript."""
    if logo_url:
        mark = f'<a href="/" class="flex items-center"><img src="{_a(logo_url)}" alt="{_a(site_name)}" class="h-8 w-auto sm:h-9"></a>'
    else:
        mark = WORDMARK
    items = []
    entries = header_entries(navigation)
    for entry in entries:
        active = _is_active(entry, pathname)
        cls = f"{HEADER_TRIGGER} {f'text-burgundy-600 {HEADER_ACTIVE}' if active else ''} {'text-burgundy-600' if entry['style'] == 'cta' else ''}"
        chevron = ICONS["chevronDown"] if entry["menu"] else ""
        current = ' aria-current="page"' if active and not entry["menu"] else ""
        if entry["link"]["kind"] == "group":
            inner = f'<span class="{cls}">{_t(entry["label"])}{chevron}</span>'
        else:
            inner = f'<a {_link_attrs(entry["link"])} class="{cls}"{current}>{_t(entry["label"])}{chevron}</a>'
        items.append(f'<li class="flex h-full">{inner}</li>')
    return (
        '<header data-wsf-header-placeholder="true" class="fixed inset-x-0 top-0 z-40 border-b border-taupe-200 bg-ivory">'
        f'<div class="{HEADER_BAR}"><div class="{HEADER_LOGO_WRAP}">{mark}</div>'
        f'<nav aria-label="Primary" class="{HEADER_NAV}"><ul class="flex h-full items-stretch">{"".join(items)}</ul></nav>'
        f'<div class="{HEADER_ACTIONS}">'
        f'<a href="/search" aria-label="Search" class="inline-block {HEADER_ICON_BUTTON}">{ICONS["search"]}</a>'
        f'<div class="hidden sm:block"><div class="relative"><a href="/login" aria-label="Sign in or create an account" '
        f'class="block {HEADER_ICON_BUTTON}">{ICONS["user"]}</a></div></div>'
        f'<a href="/newsletter" class="{HEADER_SUBSCRIBE}">Subscribe</a>'
        f'<span aria-hidden="true" class="inline-block {HEADER_MENU_BUTTON}">{ICONS["menu"]}</span>'
        "</div></div></header>"
    )


def render_noscript_nav(navigation):
    """Navigation for visitors without JavaScript (the desktop bar is hidden
    below xl and the mobile menu needs JS). Placed at the top of the page
    content; never rendered when scripting is on."""
    links = "".join(
        f'<li><a {_link_attrs(e["link"])} class="underline">{_t(e["label"])}</a></li>'
        for e in header_entries(navigation) if e["link"]["kind"] != "group"
    )
    if not links:
        return ""
    return (f'<noscript><nav aria-label="Site sections" class="container-editorial pt-4">'
            f'<ul class="flex flex-wrap gap-x-4 gap-y-1 text-sm">{links}</ul></nav></noscript>')


# --- Formatting (utils/format.js, utils/listingDates.js, utils/readingTime.js) -----------------
_MONTHS_SHORT = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"]
_MONTHS_LONG = ["January", "February", "March", "April", "May", "June", "July", "August", "September",
                "October", "November", "December"]
_WEEKDAYS_SHORT = ["Mon", "Tue", "Wed", "Thu", "Fri", "Sat", "Sun"]


def _js_round(x):
    """Math.round (halves round up), not Python's banker's rounding."""
    import math

    return int(math.floor(x + 0.5))


def _parse_date(value):
    """A calendar date from an ISO date/datetime string. The browser formats
    in the visitor's time zone; the server uses the stored (UTC) date."""
    if not isinstance(value, str) or len(value) < 10:
        return None
    try:
        if len(value) > 10:
            dt = datetime.fromisoformat(value.replace("Z", "+00:00"))
            if dt.tzinfo is not None:
                from datetime import timezone

                dt = dt.astimezone(timezone.utc)
            return dt.date()
        return date.fromisoformat(value[:10])
    except ValueError:
        return None


def format_short_date(value):
    """formatShortDate: en-US {month: short, day: numeric} -> "Nov 16"."""
    d = _parse_date(value)
    return f"{_MONTHS_SHORT[d.month - 1]} {d.day}" if d else "Invalid Date" if value else ""


def _event_day_line(value):
    """formatDate(date, {weekday: short, month: short, day: numeric}) -> "Thu, Dec 3"."""
    d = _parse_date(value)
    return f"{_WEEKDAYS_SHORT[d.weekday()]}, {_MONTHS_SHORT[d.month - 1]} {d.day}" if d else ""


def _iso_parts(value):
    if not isinstance(value, str) or len(value) < 10:
        return None
    try:
        return date(int(value[0:4]), int(value[5:7]), int(value[8:10]))
    except ValueError:
        return None


def long_date(value):
    d = _iso_parts(value)
    return f"{d.day} {_MONTHS_LONG[d.month - 1]} {d.year}" if d else ""


def short_date(value, current_year=None):
    d = _iso_parts(value)
    if not d:
        return ""
    current_year = current_year or datetime.utcnow().year
    return f"{d.day} {_MONTHS_SHORT[d.month - 1]}" + ("" if d.year == current_year else f" {d.year}")


def closing_label(closing):
    if not isinstance(closing, dict) or not isinstance(closing.get("daysLeft"), (int, float)) or isinstance(closing.get("daysLeft"), bool):
        return ""
    days = closing["daysLeft"]
    if days <= 0:
        return "Closes today"
    if days == 1:
        return "Closes tomorrow"
    return f"Closes {short_date(closing.get('closesOn'))} · {_js_num(days)} days left"


def _js_num(n):
    """Intl.NumberFormat('en-US') for the values these cards show."""
    try:
        value = float(n)
    except (TypeError, ValueError):
        return "NaN"
    if value.is_integer():
        return f"{int(value):,}"
    text = f"{value:,.3f}".rstrip("0").rstrip(".")
    return text


def format_currency(amount, currency="KES"):
    if not amount:
        return "Free"
    return f"{currency or 'KES'} {_js_num(amount)}"


def format_funding(opportunity):
    if opportunity.get("funding_value"):
        return opportunity["funding_value"]
    lo, hi, currency = opportunity.get("funding_min"), opportunity.get("funding_max"), opportunity.get("currency")
    if lo is None and hi is None:
        return None
    prefix = f"{currency} " if currency else ""
    if lo is not None and hi is not None and lo != hi:
        return f"{prefix}{_js_num(lo)}–{_js_num(hi)}"
    return f"{prefix}{_js_num(lo if lo is not None else hi)}"


def format_salary(job):
    lo, hi = job.get("salary_min"), job.get("salary_max")
    if not lo and not hi:
        return "Salary not disclosed"
    if lo and hi:
        return f"{job.get('currency')} {_js_num(lo)}–{_js_num(hi)}/{job.get('salary_period')}"
    return f"{job.get('currency')} {_js_num(lo or hi)}/{job.get('salary_period')}"


def reading_time(article):
    """resolveReadingTime for a card (summary dumps carry reading_time)."""
    try:
        explicit = float(article.get("reading_time"))
    except (TypeError, ValueError):
        explicit = 0
    return _js_round(explicit) if explicit > 0 else 1


