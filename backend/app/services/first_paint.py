def render_module(module, lead=None):
    kind = module.get("type")
    if kind == "hero":
        return _hero(module, lead)
    if kind == "latest_stories":
        return _listing(module, "articles", "Fresh this week", "/topics", "All stories", ARTICLE_GRID_4, article_card)
    if kind == "featured_stories":
        items = _init(module, "articles")
        if not items:
            return ""  # React renders nothing until its picks arrive
        return _listing(module, "articles", "Editors' picks", None, "See all", ARTICLE_GRID_4, article_card)
    if kind == "featured_woman":
        return _featured_woman(module)
    if kind == "series_feature":
        return _series(module)
    if kind == "topic_collection":
        return _topic(module)
    if kind == "opportunities":
        eyebrow = "Opening soon" if _cfg(module).get("sort") == "upcoming" else "Funding & opportunities"
        return _listing(module, "items", eyebrow, "/opportunities", "See all", "mt-8 grid grid-cols-1 gap-6 sm:grid-cols-3", opportunity_card)
    if kind == "resources":
        return _listing(module, "items", "Resource Library", "/resources", "See all", "mt-8 grid grid-cols-1 gap-8 sm:grid-cols-3",
                        resource_card, CREAM_SECTION)
    if kind == "events":
        return _listing(module, "items", "Join Us", "/events", "See all", "mt-8 grid grid-cols-1 gap-4 sm:grid-cols-3", event_card)
    if kind == "jobs":
        eyebrow = "Closing soon" if _cfg(module).get("sort") == "closing_soon" else "Careers"
        return _listing(module, "items", eyebrow, "/jobs", "See all", "mt-8 grid grid-cols-1 gap-4 sm:grid-cols-2", job_card, CREAM_SECTION)
    if kind in COLLECTION_LAYOUT:
        return _article_collection(module)
    if kind == "people_spotlight":
        return _people_spotlight(module)
    if kind == "learning":
        return _learning(module)
    if kind == "mission":
        return _mission(module)
    if kind == "newsletter":
        return _newsletter(module)
    if kind in _CALLOUTS:
        return _callout(module)
    if kind == "career_pathways":
        return _career_pathways(module)
    if kind == "content_collection":
        return _content_collection(module)
    # partners / sponsor_placement: commercial modules whose eligibility is
    # resolved client-side; their React components render after mount.
    return ""


def render_homepage(modules, lead_article=None, site_name="Women Shaping Futures"):
    """HomePage.jsx: <main class="flex-1"><div>{modules}</div></main>. The
    page H1 is the hero's (lead Article title or manual heading); without a
    hero H1 a visually hidden one names the site, in React too."""
    body = "".join(render_module(m, lead_article) for m in modules)
    hero = next((m for m in modules if m.get("type") == "hero"), None)
    hero_has_h1 = bool(hero and (_cfg(hero).get("leadArticleSlug") or hero.get("heading")))
    h1 = "" if hero_has_h1 else f'<h1 class="sr-only">{_t(site_name)}</h1>'
    return f'<main data-wsf-prerender="home" class="flex-1"><div>{h1}{body}</div></main>'


