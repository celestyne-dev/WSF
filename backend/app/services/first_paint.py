        + (f'<span class="absolute right-3 top-3 inline-flex items-center gap-1 bg-charcoal/85 px-2 py-1 text-[11px] font-semibold uppercase tracking-wide text-ivory">{ICONS[badge[0]]} {_t(badge[1])}</span>' if badge else "")
        + f'</div><div class="mt-3"><span class="eyebrow">{_t((fmt or {}).get("label") or r.get("type"))}</span>'
        f'<h3 class="mt-1 font-serif text-lg font-semibold leading-snug text-charcoal transition-colors group-hover:text-burgundy-600">{_t(r.get("name"))}</h3>'
