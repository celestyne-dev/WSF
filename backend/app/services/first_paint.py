def _js_number_text(value):
    """String(number) for the finite values the placeholder uses."""
    if float(value).is_integer():
        return str(int(value))
    return repr(float(value))


def _hash_seed(seed):
    h = 0
    for unit in _utf16_units(str(seed)):  # String.charCodeAt: UTF-16 code units
        h = (h * 31 + unit) & 0xFFFFFFFF
    return h


def _utf16_units(text):
    data = text.encode("utf-16-le")
    return [data[i] | (data[i + 1] << 8) for i in range(0, len(data), 2)]


def svg_placeholder(seed="placeholder", width=1200, height=800, tone=None):
    """Byte-identical port of utils/media.js svgPlaceholder()."""
    h = _hash_seed(seed)
    keys = list(_TONES)
    chosen = tone if tone in _TONES else keys[h % len(keys)]
    c1, c2, c3 = _TONES[chosen]
    angle = h % 360
    cx = 15 + (h % 55)
    cy = 15 + ((h >> 3) % 55)
    r = 38 + (h % 26)
    svg = (
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" viewBox="0 0 100 {_js_number_text((100 * height) / width)}">\n'
        "  <defs>\n"
        f'    <linearGradient id="g" x1="0%" y1="0%" x2="100%" y2="100%" gradientTransform="rotate({angle} 50 50)">\n'
        f'      <stop offset="0%" stop-color="{c1}"/>\n'
        f'      <stop offset="100%" stop-color="{c2}"/>\n'
        "    </linearGradient>\n"
        "  </defs>\n"
        '  <rect width="100%" height="100%" fill="url(#g)"/>\n'
        f'  <circle cx="{cx}%" cy="{cy}%" r="{r}%" fill="{c3}" fill-opacity="0.16"/>\n'
        f'  <circle cx="{100 - cx}%" cy="{100 - cy}%" r="{_js_number_text(r * 0.55)}%" fill="{c3}" fill-opacity="0.12"/>\n'
        "</svg>"
    )
    return "data:image/svg+xml;utf8," + quote(svg, safe="-_.!~*'()")


def _is_backend_path(value):
    return isinstance(value, str) and (value.lower().startswith(("http://", "https://")) or value.startswith("/"))


def resolve_media(media, variant, width, height, tone=None):
    """resolveMediaImage()/resolveImage(): (src, srcset or None). URLs stay
    root-relative: the browser resolves them to the same absolute URL React
    builds (API_ORIGIN is the page origin in production)."""
    if not media:
        return svg_placeholder("placeholder", width, height, tone), None
    variants = media.get("variants") if isinstance(media.get("variants"), dict) else {}
    real = [(name, v) for name, v in variants.items()
            if isinstance(v, dict) and v.get("url") and isinstance(v.get("width"), (int, float))
            and not isinstance(v.get("width"), bool) and v["width"] > 0 and _is_backend_path(v["url"])]
    if real:
        preferred = variants.get(variant) if isinstance(variants.get(variant), dict) else None
        src = preferred["url"] if preferred and preferred.get("url") and _is_backend_path(preferred["url"]) else real[0][1]["url"]
        by_width = {}
        for _name, v in real:
            by_width[v["width"]] = v["url"]
        srcset = ", ".join(f"{url} {_js_number_text(w)}w" for w, url in sorted(by_width.items()))
        return src, srcset
    path = media.get("public_url")
    if _is_backend_path(path):
        return path, None
    return svg_placeholder("placeholder", width, height, tone), None


def media_img(media, *, variant="card", alt="", width=1200, height=800, aspect=None, sizes=None, tone=None,
              class_name="", priority=False):
    """<MediaImage> markup. A placeholder omits the (all-identical-looking)
    placeholder srcset to keep the HTML small."""
    ratio = aspect or width / height
    computed_height = _js_round(width / ratio)
    src, srcset = resolve_media(media, variant, width, computed_height, tone)
    resolved_sizes = sizes or ("100vw" if priority else f"{width}px")
    attrs = [f'src="{_a(src)}"']
    if srcset:
        attrs.append(f'srcset="{_a(srcset)}"')
    attrs += [f'sizes="{_a(resolved_sizes)}"', f'alt="{_a(alt)}"', f'width="{width}"', f'height="{computed_height}"',
              f'loading="{"eager" if priority else "lazy"}"']
    if priority:
        attrs.append('fetchpriority="high"')
    attrs += ['decoding="async"', f'class="{_a(class_name)}"']
    return f"<img {' '.join(attrs)}>"


def _alt(media, fallback):
    """resolveAltText()."""
    return (media or {}).get("alt_text") or fallback or ""


