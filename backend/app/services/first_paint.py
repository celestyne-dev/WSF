def _pathway_link(card):
    if not card.get("href"):
        return None
    link = public_nav_link({"url": card["href"], "linkType": card.get("linkType"), "openNewTab": card.get("openNewTab")})
    return None if not link or link["kind"] == "group" else link


def _career_pathways(module):
    cards = [c for c in ((module.get("resolved") or {}).get("cards") or []) if _pathway_link(c)]
    if not cards:
        return ""
    tiles = []
    for card in cards:
        link = _pathway_link(card)
        image = card.get("image") or None
        icon = ICONS.get(f"pathway:{card.get('icon')}") if card.get("icon") else None
        if image:
            dims = "".join(f' {k}="{_a(image[k])}"' for k in ("width", "height") if image.get(k))
            visual = f'<img src="{_a(image.get("url"))}" alt=""{dims} loading="lazy" class="mb-4 aspect-[16/9] w-full object-cover">'
        elif icon:
            visual = ('<span class="mb-4 inline-flex h-11 w-11 items-center justify-center rounded-full bg-taupe-100 text-burgundy-600 '
                      f'transition-colors group-hover:bg-burgundy-600 group-hover:text-white">{icon}</span>')
        else:
            visual = ""
        body = (
            visual
            + (f'<p class="eyebrow mb-1.5">{_t(card["eyebrow"])}</p>' if card.get("eyebrow") else "")
            + f'<h3 class="break-words font-serif text-xl font-semibold leading-snug text-charcoal group-hover:text-burgundy-700">{_t(card.get("title"))}</h3>'
            + (f'<p class="mt-2 break-words text-sm leading-relaxed text-charcoal-600">{_t(card["description"])}</p>' if card.get("description") else "")
            + f'<span class="mt-auto flex justify-end pt-4 text-burgundy-600" aria-hidden="true">{ICONS["arrowUpRight18"]}</span>'
        )
        aria = f' aria-label="{_a(card["ariaLabel"])}"' if card.get("ariaLabel") else ""
        tiles.append(f'<li class="min-w-0"><a {_link_attrs(link)}{aria} class="{PATHWAY_TILE}">{body}</a></li>')
    heading = section_heading(_cfg(module).get("eyebrow"), module.get("heading"), module.get("subheading"))
    columns = _PATHWAY_COLUMNS.get(len(cards), "lg:grid-cols-4")
    return _section(CREAM_SECTION, f'{heading}<ul class="mt-8 grid grid-cols-1 gap-4 sm:grid-cols-2 {columns}">{"".join(tiles)}</ul>'
                    + section_cta_link(module.get("cta_label"), module.get("cta_url")))


