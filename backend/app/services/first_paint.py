def slugify_heading(text):
    """utils/headingToc.js slugifyHeading."""
    import re

    base = re.sub(r"\s+", "-", re.sub(r"[^a-z0-9\s-]", "", (text or "").lower()).strip())[:60]
    return base or "section"


def article_heading_ids(blocks):
    """buildHeadingToc ids, by block index ("-2", "-3" for repeats)."""
    seen, ids = {}, {}
    for i, block in enumerate(blocks):
        if block.get("type") != "heading" or not (block.get("text") or "").strip():
            continue
        base = slugify_heading(block["text"])
        count = seen.get(base, 0)
        seen[base] = count + 1
        ids[i] = base if count == 0 else f"{base}-{count + 1}"
    return ids


def _toc_entries(blocks):
    ids = article_heading_ids(blocks)
    entries = [{"id": ids[i], "text": b["text"], "level": b.get("level") or 2}
               for i, b in enumerate(blocks) if i in ids and (b.get("level") or 2) in (2, 3)]
    return entries if len(entries) >= ARTICLE_TOC_MIN_HEADINGS else []


