def _format_minutes(minutes):
    try:
        total = _js_round(float(minutes or 0))
    except (TypeError, ValueError):
        total = 0
    if total <= 0:
        return ""
    hours, mins = divmod(total, 60)
    if not hours:
        return f"{mins} min"
    return f"{hours} hr {mins} min" if mins else f"{hours} hr"


