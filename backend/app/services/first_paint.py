def _section(section_class, inner, container="container-editorial"):
    return f'<section class="{section_class}"><div class="{container}">{inner}</div></section>'


def _cfg(module):
    return module.get("config") or {}


def _init(module, key):
    data = module.get("initial_data")
    return data.get(key) if isinstance(data, dict) else None


def _item_count(module, default):
    return _cfg(module).get("itemCount") or default


def _hero(module, lead):
    """HeroModule.jsx. The lead is the page selection's (`initial_data.lead`,
    null when unpublished or placed earlier); without initial data, the
    bootstrap lead when it matches the configured slug."""
    cfg = _cfg(module)
    data = module.get("initial_data")
    decided = isinstance(data, dict) and "lead" in data
    if decided:
        lead = data["lead"]
    elif lead is not None and lead.get("slug") != cfg.get("leadArticleSlug"):
        lead = None
    if lead is not None:
        card = article_card({**lead, "title": module["heading"]} if module.get("heading") else lead, "lead", heading_level=1)
        cta = (cta_link(module["cta_url"], "btn-outline mt-4 inline-flex", module["cta_label"])
               if module.get("cta_label") and module.get("cta_url") else "")
        secondary = "".join(article_card(a, "horizontal") for a in _init(module, "secondary") or [])
        return (
            '<section class="border-b border-taupe-200 bg-ivory py-10 sm:py-14">'
            '<div class="container-editorial grid grid-cols-1 gap-10 lg:grid-cols-3">'
            f'<div class="lg:col-span-2">{card}{cta}</div>'
            f'<div class="flex flex-col gap-6 lg:border-l lg:border-taupe-200 lg:pl-10">{secondary}</div></div></section>'
        )
    if cfg.get("leadArticleSlug") and not decided:
        return ""  # React waits on the lead Article (renders nothing yet)
    if not module.get("heading"):
        return ""
    ctas = ""
    if module.get("cta_label") and module.get("cta_url"):
        ctas += cta_link(module["cta_url"], "btn-primary", module["cta_label"])
    if module.get("secondary_cta_label") and module.get("secondary_cta_url"):
        ctas += cta_link(module["secondary_cta_url"], "btn-outline", module["secondary_cta_label"])
    media = module.get("media") or None
    img = (media_img(media, variant="hero", alt=media.get("alt_text") or module["heading"], width=1200, height=800, aspect=3 / 2,
                     sizes="(min-width: 1024px) 50vw, 100vw", priority=True, class_name="aspect-[3/2] w-full object-cover")
           if media else "")
    return (
        '<section class="border-b border-taupe-200 bg-ivory py-14 sm:py-20">'
        '<div class="container-editorial grid grid-cols-1 items-center gap-10 lg:grid-cols-2"><div>'
        f'<h1 class="font-serif text-4xl font-semibold leading-tight text-charcoal sm:text-5xl">{_t(module["heading"])}</h1>'
        + (f'<p class="mt-4 max-w-xl text-lg text-charcoal-600">{_t(module["subheading"])}</p>' if module.get("subheading") else "")
        + f'<div class="mt-7 flex flex-wrap gap-3">{ctas}</div></div>{img}</div></section>'
    )


def _listing(module, key, eyebrow, view_all, label, grid, render, section_class=GRID_SECTION):
    items = _init(module, key)
    if items is not None and not items:
        return ""
    heading = section_heading(eyebrow, module.get("heading"), module.get("subheading"), view_all, label)
    return _section(section_class, f'{heading}<div class="{grid}">{"".join(render(i) for i in items or [])}</div>')


