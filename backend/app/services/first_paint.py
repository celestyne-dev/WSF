def _api(method, path, params=None, body=None):
    """The JSON body the public API returns for this anonymous request, by
    dispatching it to the same view inside this process (no HTTP, no
    auth), or None if it is not a success."""
    from flask import current_app
    from werkzeug.exceptions import HTTPException

    from app.extensions import db
    from app.utils.responses import ApiError

    try:
        with current_app.test_request_context(f"/api/v1{path}", method=method, query_string=params, json=body):
            response = current_app.make_response(current_app.dispatch_request())
            if response.status_code == 404:
                return NOT_FOUND
            if response.status_code != 200:
                return None
            payload = response.get_json(silent=True)
    except (ApiError, HTTPException) as exc:
        # A 404 (a slug that is not public) is an answer, not a failure: the
        # component treats it as "nothing to show", so it is passed on.
        return NOT_FOUND if getattr(exc, "status", getattr(exc, "code", None)) == 404 else None
    except Exception:  # noqa: BLE001 - a module without first-paint data falls back to its own fetch
        db.session.rollback()
        current_app.logger.warning("first paint: %s %s failed", method, path, exc_info=True)
        return None
    return payload if isinstance(payload, dict) and payload.get("success") else None


def _data(payload, key=None):
    if payload is None or payload == NOT_FOUND:
        return None
    data = payload.get("data")
    return data.get(key) if key and isinstance(data, dict) else data


def homepage_initial_data(module):
    """What `module`'s React component fetches on mount, fetched here with
    the component's own parameters, so its first frame already has it.
    Keys match the components' `module.initialData` reads."""
    cfg = _cfg(module)
    kind = module.get("type")
    count = cfg.get("itemCount")
    if kind == "hero":
        slugs = cfg.get("secondaryArticleSlugs") or []
        data = _data(_api("POST", "/articles/related", body={"slugs": slugs})) if slugs else []
        return None if data is None else {"secondary": data}
    if kind == "latest_stories":
        data = _data(_api("GET", "/articles", {"per_page": count or 8}))
        return None if data is None else {"articles": data}
    if kind == "featured_stories":
        slugs = cfg.get("articleSlugs") or []
        data = _data(_api("POST", "/articles/related", body={"slugs": slugs})) if slugs else []
        return None if data is None else {"articles": data}
    if kind == "featured_woman" and cfg.get("personSlug"):
        response = _api("GET", f"/people/{quote(str(cfg['personSlug']), safe='')}")
        if response == NOT_FOUND:
            return {"person": None}  # fetchPersonBySlug's own 404 result
        person = _data(response)
        # Only what FeaturedWomanModule shows: a profile's credentials and
        # other detail-page evidence stay off the homepage (GEO Phase 4B).
        card = {k: person.get(k) for k in _FEATURED_PERSON_FIELDS} if isinstance(person, dict) else None
        return {"person": card} if card else None
    if kind in ("series_feature", "topic_collection"):
        key, rel, path = ("seriesSlug", "series", "/series/") if kind == "series_feature" else ("topicSlug", "topic", "/topics/")
        slug = cfg.get(key)
        if not slug:
            return None
        response = _api("GET", path + quote(str(slug), safe=""))
        if response == NOT_FOUND:
            return {rel: None}  # fetchSeriesBySlug/fetchTopicBySlug's own 404 result
        term = _data(response, rel)
        if not term:
            return None
        articles = _data(_api("GET", "/articles", {rel: slug, "per_page": count or 3}))
        return {rel: term, **({"articles": articles} if articles is not None else {})}
    listings = {
        "opportunities": ("/opportunities", {"scope": "public", "featured": "true", "per_page": count or 3}),
        "resources": ("/resources", {"featured": "true", "per_page": count or 3}),
        "events": ("/events", {"per_page": count or 3}),
        "jobs": ("/jobs", {"scope": "public", "featured": "true", "per_page": count or 4}),
    }
    if kind in listings:
        data = _data(_api("GET", *listings[kind]))
        return None if data is None else {"items": data}
    if kind == "newsletter":
        stats = _data(_api("GET", "/newsletter/stats"))
        if not isinstance(stats, dict):
            return None
        return {"subscriberCount": stats.get("subscriberCount") if stats.get("subscriberCount") is not None else 0}
    return None


